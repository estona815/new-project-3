PRESETS = (
    "Bypass",
    "DSP Only",
    "DSP Only Safe",
    "Preserve",
    "Balanced",
    "Surgical AI Artifact",
    "AI Metallic Surgical",
    "Hiss / Room Tone Gentle",
    "Voiceover Clean",
    "Side Noise Cleanup",
    "Artifact Focus Low Denoise",
    "Strong Test",
    "Strong Test / Repair",
)


def preset_slug(preset: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9._-]+", "_", preset).strip("_")
    return slug or "preset"


def load_manifest(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def resolve_audio_path(manifest_path: Path, item: dict[str, Any]) -> Path:
    path = Path(item["path"])
    return path if path.is_absolute() else manifest_path.parent / path


def write_single_input_manifest(input_path: Path, output_dir: Path) -> Path:
    resolved = input_path.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "schema": "codex-vocal-ab-eval-manifest-v1",
        "description": "Single-file evaluation manifest generated by evaluation_harness.",
        "items": [
            {
                "id": preset_slug(resolved.stem),
                "path": str(resolved),
                "category": "user_supplied",
                "source_type": "unknown",
                "contains_vocal": False,
                "contains_transients": False,
                "contains_stereo_ambience": False,
                "has_noise": False,
                "has_ai_artifact": False,
                "expected_behavior": "mixed",
                "protected_bands": ["presence", "clarity", "air"],
                "notes": "Generated from --input. Update metadata in a manifest for stricter evaluation.",
            }
        ],
    }
    manifest_path = output_dir / "single_input_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest_path


def resolve_processed_path(processed_dir: Path | None, item: dict[str, Any], preset: str, manifest_path: Path) -> Path | None:
    explicit = item.get("processed_path")
    if explicit:
        p = Path(explicit)
        return p if p.is_absolute() else manifest_path.parent / p
    if not processed_dir:
        return None
    slug = preset_slug(preset)
    candidates = [
        processed_dir / slug / item["id"] / "processed.wav",
        processed_dir / slug / f"{item['id']}.wav",
        processed_dir / preset / item["id"] / "processed.wav",
        processed_dir / preset / f"{item['id']}.wav",
        processed_dir / f"{item['id']}_processed.wav",
        processed_dir / f"{item['id']}.wav",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return None


def render_item(
    original: AudioBuffer,
    *,
    renderer: str,
    processed_path: Path | None,
) -> AudioBuffer:
    if renderer == "external":
        if not processed_path:
            raise FileNotFoundError("external renderer requires processed_path or --processed-dir")
        processed = read_wav(processed_path)
        if processed.sample_rate != original.sample_rate:
            raise ValueError(f"processed sample rate {processed.sample_rate} differs from original {original.sample_rate}")
        x, y = align_pair(original.samples, processed.samples)
        return AudioBuffer(original.sample_rate, y)
    if renderer == "passthrough":
        return AudioBuffer(original.sample_rate, original.samples.copy())
    raise ValueError(f"unsupported renderer: {renderer}")


def write_item_report(path: Path, item: dict[str, Any], preset: str, metrics: dict[str, Any], files: dict[str, str]) -> None:
    lines = [
        f"# {item['id']} - {preset}",
        "",
        f"- Category: `{item.get('category', 'unknown')}`",
        f"- Expected behavior: `{item.get('expected_behavior', 'unknown')}`",
        f"- Status: **{metrics['status']}**",
        f"- Renderer: `{metrics.get('renderer', 'unknown')}`",
        f"- Block size: `{metrics.get('block_size', 'unknown')}`",
        f"- Sample rate: `{metrics.get('sample_rate', 'unknown')}`",
        f"- Residual definition: `{metrics.get('residual_definition', 'inputAligned - processedAligned')}`",
        f"- Processed matched gain: `{metrics['level']['matched_gain_db']:.2f} dB`",
        "",
        "## Listening",
        "",
        f"- Original: [{Path(files['original']).name}]({files['original']})",
        f"- Processed: [{Path(files['processed']).name}]({files['processed']})",
        f"- Processed matched: [{Path(files['processed_matched']).name}]({files['processed_matched']})",
        f"- Residual: [{Path(files['residual']).name}]({files['residual']})",
        "",
        "## Key Metrics",
        "",
        f"- Presence loss: `{metrics['metrics']['presence_loss_db']:.2f} dB`",
        f"- Clarity loss: `{metrics['metrics']['clarity_loss_db']:.2f} dB`",
        f"- Air loss: `{metrics['metrics']['air_loss_db']:.2f} dB`",
        f"- Spectral tilt loss: `{metrics['metrics']['spectral_tilt_loss_db']:.2f} dB`",
        f"- Transient peak loss: `{metrics['metrics']['transient_peak_loss_db']:.2f} dB`",
        f"- Residual source leakage: `{metrics['metrics']['residual_source_leakage_score']:.2f}`",
        f"- Stereo width change: `{metrics['metrics']['stereo_width_change_db']:.2f} dB`",
        "",
        "## Warnings",
        "",
    ]
    warnings = metrics.get("warnings", []) + metrics.get("failures", [])
    if warnings:
        lines.extend(f"- `{warning}`" for warning in warnings)
    else:
        lines.append("- none")
    lines.extend(
        [
            "",
            "## Listening Checklist",
            "",
            "- Does vocal/source move backward?",
            "- Are consonants intact?",
            "- Is air preserved?",
            "- Are transients intact?",
            "- Does residual contain ghost vocal/source?",
            "- Would less denoise sound better?",
            "",
            "## Human Notes",
            "",
            "- ",
        ]
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_run_report(path: Path, run_report: dict[str, Any]) -> None:
    lines = [
        f"# A/B Evaluation - {run_report['preset']}",
        "",
        f"- Renderer: `{run_report['renderer']}`",
        f"- Block size: `{run_report['block_size']}`",
        f"- Files: `{len(run_report['files'])}`",
        f"- Pass: `{run_report['summary']['pass_count']}`",
        f"- Warning: `{run_report['summary']['warning_count']}`",
        f"- Fail: `{run_report['summary']['fail_count']}`",
        "",
        "## Results",
        "",
        "| ID | Category | Status | Overall | Preservation | Residual | Warnings |",
        "| --- | --- | --- | ---: | ---: | ---: | --- |",
    ]
    for entry in run_report["files"]:
        warnings = ", ".join(entry.get("warnings", []) + entry.get("failures", [])) or "none"
        lines.append(
            f"| {entry['id']} | {entry.get('category', 'unknown')} | {entry['status']} | "
            f"{entry['scores']['overall']:.1f} | {entry['scores']['source_preservation']:.1f} | "
            f"{entry['scores']['residual_cleanliness']:.1f} | {warnings} |"
        )
    lines.extend(
        [
            "",
            "## Residual Definition",
            "",
            "`residual.wav = original input aligned to processed length - processed.wav`.",
            "The current JSFX reports zero plugin latency, so no latency compensation is applied in this foundation harness.",
            "",
            "## Listening Protocol",
            "",
            "1. Listen to original.",
            "2. Listen to processed matched.",
            "3. Switch A/B quickly.",
            "4. Listen to residual prominently.",
            "5. Fail any result where residual contains ghost vocal, consonants, harmonics, attacks, or source ambience.",
        ]
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_evaluation(
    manifest_path: Path,
    *,
    preset: str,
    output_dir: Path,
    renderer: str = "passthrough",
    processed_dir: Path | None = None,
    block_size: int = 512,
    fail_on_damage: bool = False,
) -> dict[str, Any]:
    manifest = load_manifest(manifest_path)
    output_dir.mkdir(parents=True, exist_ok=True)
    files_report: list[dict[str, Any]] = []
    preset_dir = output_dir / preset_slug(preset)

    for item in manifest.get("items", []):
        item_id = item["id"]
        item_out = preset_dir / item_id
        item_out.mkdir(parents=True, exist_ok=True)
        original_path = resolve_audio_path(manifest_path, item)
        original = read_wav(original_path)
        processed_path = resolve_processed_path(processed_dir, item, preset, manifest_path)
        processed = render_item(original, renderer=renderer, processed_path=processed_path)
        x, y = align_pair(original.samples, processed.samples)
        original = AudioBuffer(original.sample_rate, x)
        processed = AudioBuffer(processed.sample_rate, y)
        residual = AudioBuffer(original.sample_rate, original.samples - processed.samples)
        matched_samples, matched_gain_db = loudness_match(original.samples, processed.samples)
        matched = AudioBuffer(original.sample_rate, matched_samples)

        original_out = item_out / "original.wav"
        processed_out = item_out / "processed.wav"
        matched_out = item_out / "processed_matched.wav"
        residual_out = item_out / "residual.wav"
        if original_path.resolve() != original_out.resolve():
            write_wav(original_out, original)
        else:
            shutil.copyfile(original_path, original_out)
        write_wav(processed_out, processed)
        write_wav(matched_out, matched)
        write_wav(residual_out, residual)

        metrics = evaluate_pair(
            original,
            processed,
            preset=preset,
            expected_behavior=item.get("expected_behavior", "mixed"),
        )
        metrics["level"]["matched_gain_db"] = matched_gain_db
        metrics["level"]["match_gain_db"] = matched_gain_db
        metrics["id"] = item_id
        metrics["input"] = str(original_path)
        metrics["preset"] = preset
        metrics["renderer"] = renderer
        metrics["sample_rate"] = original.sample_rate
        metrics["block_size"] = block_size
        metrics["latency_samples"] = 0
        metrics["residual_definition"] = "inputAligned - processedAligned"
        metrics["category"] = item.get("category", "unknown")
        metrics["source_type"] = item.get("source_type", "unknown")
        metrics["expected_behavior"] = item.get("expected_behavior", "unknown")
        metrics["files"] = {
            "original": "original.wav",
            "processed": "processed.wav",
            "processed_matched": "processed_matched.wav",
            "residual": "residual.wav",
        }
        save_json(item_out / "metrics.json", metrics)
        write_item_report(item_out / "report.md", item, preset, metrics, metrics["files"])
        files_report.append(metrics)

    summary = {
        "pass_count": sum(1 for entry in files_report if entry["status"] == "pass"),
        "warning_count": sum(1 for entry in files_report if entry["status"] == "warning"),
        "fail_count": sum(1 for entry in files_report if entry["status"] == "fail"),
    }
    run_report = {
        "schema": "codex-vocal-ab-eval-report-v1",
        "run_id": f"{preset.replace(' ', '_').lower()}_{renderer}_{block_size}",
        "plugin_version": "jsfx-codex-vocal-ai-artifact-split-tamer",
        "model_version": "none",
        "preset": preset,
        "renderer": renderer,
        "block_size": block_size,
        "latency_samples": 0,
        "residual_definition": "inputAligned - processedAligned",
        "manifest": str(manifest_path),
        "files": files_report,
        "summary": summary,
    }
    save_json(preset_dir / "run_metrics.json", run_report)
    write_run_report(preset_dir / "index.md", run_report)
    if fail_on_damage and summary["fail_count"] > 0:
        raise SystemExit(2)
    return run_report


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Run preservation-first A/B quality evaluation.")
    parser.add_argument("--manifest", type=Path, help="Audio test manifest JSON.")
    parser.add_argument("--input", type=Path, help="Evaluate one input WAV by generating a temporary single-file manifest in the output directory.")
    parser.add_argument("--preset", choices=PRESETS, default="Preserve")
    parser.add_argument("--output-dir", type=Path, default=Path("eval_outputs"))
    parser.add_argument("--renderer", choices=("passthrough", "external"), default="passthrough")
    parser.add_argument("--processed-dir", type=Path)
    parser.add_argument("--block-size", type=int, default=512)
    parser.add_argument("--fail-on-damage", action="store_true")
    parser.add_argument("--generate-synthetic", type=Path, help="Generate CI-safe synthetic assets at this directory and evaluate them.")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    manifest_path = args.manifest
    if args.input:
        manifest_path = write_single_input_manifest(args.input, args.output_dir)
    if args.generate_synthetic:
        generate_synthetic_suite(args.generate_synthetic)
        manifest_path = args.generate_synthetic / "manifest.synthetic.json"
    if not manifest_path:
        raise SystemExit("--manifest or --generate-synthetic is required")
    run_evaluation(
        manifest_path,
        preset=args.preset,
        output_dir=args.output_dir,
        renderer=args.renderer,
        processed_dir=args.processed_dir,
        block_size=args.block_size,
        fail_on_damage=args.fail_on_damage,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
